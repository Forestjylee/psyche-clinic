#!/usr/bin/env node
/**
 * 患者池聚合索引生成器
 *
 * 扫描 lib/data/patients/ 下的患者剧本文件，生成 lib/data/patients/index.generated.ts
 * （显式模块映射）。新增剧本（v3 转换器生成 / 手写）放进该目录后，运行
 * `npm run dev` / `npm test` / `npm run build`（predev / pretest / prebuild 钩子）
 * 即自动纳入池，无需手改聚合入口（lib/data/patients.ts）。
 *
 * 为什么不用 import.meta.glob：那是 Vite 特性，Next.js（webpack）运行时没有，
 * 会导致浏览器端 `{}.glob is not a function`。生成式显式映射在 webpack 与
 * vitest（Vite）双端可用。
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, "..");
const PATIENTS_DIR = join(REPO, "lib", "data", "patients");
const OUT_FILE = join(PATIENTS_DIR, "index.generated.ts");

// 排除聚合索引自身（以及未来的非剧本辅助文件）
const EXCLUDE = new Set(["index.generated.ts"]);

const files = readdirSync(PATIENTS_DIR)
  .filter((f) => f.endsWith(".ts") && !EXCLUDE.has(f))
  .sort();

// 文件名转合法 TS 标识符（防御 kebab/点号命名）
const ident = (name) => name.replace(/[^\w]/g, "_");

const imports = files
  .map((f) => `import * as m_${ident(f.replace(/\.ts$/, ""))} from "./${f.replace(/\.ts$/, "")}";`)
  .join("\n");

const entries = files
  .map((f) => `  ${f.replace(/\.ts$/, "")}: m_${ident(f.replace(/\.ts$/, ""))},`)
  .join("\n");

const ts = `// AUTO-GENERATED by scripts/scan-patients.mjs — 勿手改
// 源：lib/data/patients/ 下所有患者剧本文件（新增剧本放入即自动进池）
// 重新生成：\`npm run dev\` / \`npm test\` / \`npm run build\`（predev / pretest / prebuild 钩子）
import type { PatientScenario } from "../../types";

/** 判定一个模块导出值是否为患者剧本（导出名不统一：patient / patientA / patientG…） */
function isPatientScenario(x: unknown): x is PatientScenario {
  if (!x || typeof x !== "object") return false;
  const p = x as Partial<PatientScenario>;
  return (
    typeof p.id === "string" &&
    typeof p.startNode === "string" &&
    !!p.dialogues
  );
}

${imports}

const modules: Record<string, unknown> = {
${entries}
};

export const collected: PatientScenario[] = Object.values(modules)
  .flatMap((m) => Object.values(m as Record<string, unknown>))
  .filter(isPatientScenario);
`;

writeFileSync(OUT_FILE, ts, "utf8");
console.log(`✓ 生成 ${OUT_FILE}（${files.length} 个患者剧本文件）`);
