#!/usr/bin/env node
/**
 * 剧本 markdown → 患者 TS 转换器（v3 剧本格式）
 *
 * 用法：
 *   node scripts/md-to-patient.mjs docs/stories/xxx-v3.md [--out lib/data/patients] [--walk]
 *
 * 输入：v3 剧本 markdown（规范见 docs/stories/剧本编写提示词.md「输出格式规范」）
 *   - 恰好一个 ```ts-meta 代码块：完整 PatientScenario 对象字面量（除 dialogues），首行注释 `// id: <场景id>`
 *   - 一个或多个 ```ts-dialog 代码块：单个 DialogueNode 对象字面量，首行注释 `// id: <节点id>`
 *   - 其余 markdown 是给人类读的叙事说明，不参与解析
 *
 * 输出：lib/data/patients/<id>.ts —— 一个 `export const patient: PatientScenario` 模块，
 * 由聚合入口 lib/data/patients.ts re-export 命名。
 *
 * 结构校验（不通过即带行号退出 1）：
 *   - ts-meta 恰好一个；ts-dialog 至少一个
 *   - 节点 id 唯一；每个 ts-dialog 首行注释 id 与对象内 id 字段一致
 *   - startNode 存在；所有 next/autoNext 引用都有对应节点（无悬空）
 *   - 患者口述（speaker=patient）文本零叙事性时间词（第二天/一个月后/后来有一天 等）
 *   - 每个 doctor 节点 choice 都有 next；结局节点带 endingType/endingReward
 *   - 渲染成 TS 后 tsc --noEmit 全库通过（类型兜底，枚举/结构错误在这里暴露）
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve, join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, "..");
const DEFAULT_OUT = join(REPO, "lib", "data", "patients");

// 叙事性时间词（患者口述禁用；narration 过场允许）
const TIME_WORDS = [
  "第二天", "第三天", "一个月后", "两个月后", "三个月后", "半年后", "一年后",
  "两年后", "后来有一天", "过了几天", "过了些日子", "过了一阵子", "那以后没多久",
  "次日", "隔天", "下个星期", "下个月", "上周", "下周",
];
// 中文引号内的时间词误伤排除较难，这里只匹配「叙事性」短语，日常口语的「这几天/这周」不拦。

/** 解析 ts-meta / ts-dialog 围栏代码块 */
function extractFencedBlocks(src) {
  const re = /```ts-meta\s*\n([\s\S]*?)```|```ts-dialog\s*\n([\s\S]*?)```/g;
  const meta = [];
  const dialogs = [];
  let m;
  const lines = src.split("\n");
  while ((m = re.exec(src)) !== null) {
    const startLine = src.slice(0, m.index).split("\n").length;
    if (m[1] !== undefined) meta.push({ code: m[1], startLine });
    else dialogs.push({ code: m[2], startLine });
  }
  void lines;
  return { meta, dialogs };
}

/** 从代码块首行注释取 id（`// id: xxx`），并校验与对象内 id 字段一致 */
function readBlockId(block, kind) {
  const firstLine = block.code.split("\n")[0] ?? "";
  const m = firstLine.match(/^\/\/\s*id:\s*(\S+)/);
  if (!m) {
    console.error(`[${kind}] ${block.startLine} 行：代码块首行必须是注释 \`// id: <id>\``);
    process.exit(1);
  }
  const id = m[1];
  // 对象内 id 字段必须与注释一致
  const inner = block.code.match(/id\s*:\s*["'`]([^"'`]+)["'`]/);
  if (inner && inner[1] !== id) {
    console.error(`[${kind}] ${block.startLine} 行：注释 id 为 "${id}"，对象内 id 为 "${inner[1]}"，不一致`);
    process.exit(1);
  }
  if (!inner) {
    console.error(`[${kind}] ${block.startLine} 行：对象字面量缺少 id 字段（应写 id: "${id}"）`);
    process.exit(1);
  }
  return id;
}

/** 正则提取字符串字段（首处匹配；单行字符串/模板串） */
function field(obj, name) {
  const re = new RegExp(name + '\\s*:\\s*(["\'`])([\\s\\S]*?)\\1');
  const m = obj.match(re);
  return m ? m[2] : undefined;
}
function numField(obj, name) {
  const m = obj.match(new RegExp(`${name}\\s*:\\s*(-?\\d+)`));
  return m ? Number(m[1]) : undefined;
}

/** 收集对象字面量里的 next / autoNext 引用 */
function collectRefs(dialogCode) {
  const refs = [];
  for (const n of ["next", "autoNext"]) {
    const re = new RegExp(n + '\\s*:\\s*["\'`]([^"\'`]+)["\'`]', "g");
    let m;
    while ((m = re.exec(dialogCode)) !== null) refs.push({ kind: n, to: m[1] });
  }
  return refs;
}

/** 解析 ts-meta 首部的验证参数注释（`// key: value`，对象字面量之前） */
function parseMetaComments(code) {
  const objStart = code.indexOf("{");
  const head = objStart >= 0 ? code.slice(0, objStart) : code;
  const out = {};
  for (const line of head.split("\n")) {
    const m = line.match(/\/\/\s*(\w+)\s*:\s*(.+)/);
    if (!m) continue;
    const [, k, v] = m;
    const val = v.trim();
    if (k === "anchor") out.anchor = val.split(",").map(Number);
    else if (["truthEnd", "minCureRounds", "fragments", "worsenAtMost"].includes(k)) out[k] = Number(val);
    else out[k] = val;
  }
  return out;
}

/** 生成 --walk 走线验收测试 */
function buildWalkTest(sceneId, name, tier, p) {
  const anchorLast = p.anchor?.length ? p.anchor[p.anchor.length - 1] : 0;
  const minRounds = p.minCureRounds ?? 0;
  const fragments = p.fragments ?? 0;
  const worsen = p.worsenAtMost ?? 0;
  const truthEnd = p.truthEnd ?? 0;
  return `// AUTO-GENERATED by scripts/md-to-patient.mjs --walk — 勿手改（源：剧本 v3 markdown）
import { describe, it, expect } from "vitest";
import { patient } from "./patients/${sceneId}";
import { walkScenario, PICKS } from "../engine/walk";

describe("${name} 剧本走线验证（${tier}剧本）", () => {
  it("共情线 → cure，trust 达锚点末位 ${anchorLast}，轮数 ≥ ${minRounds}", () => {
    const r = walkScenario(patient, PICKS.empathy);
    expect(r.ending).toBe("cure");
    expect(r.trust).toBe(${anchorLast});
    expect(r.rounds).toBeGreaterThanOrEqual(${minRounds});
  });
  it("均衡线 → cure，碎片触发 ≥ ${fragments}", () => {
    const r = walkScenario(patient, PICKS.balanced);
    expect(r.ending).toBe("cure");
    expect(r.memories.length).toBeGreaterThanOrEqual(${fragments});
  });
  it("失误线 → worsen，trust ≤ ${worsen}（恶化入口可见）", () => {
    const r = walkScenario(patient, PICKS.mistake);
    expect(r.ending).toBe("worsen");
    expect(r.trust).toBeLessThanOrEqual(${worsen});
  });
  it("探问线 → cure，truth 冲顶 ≥ ${truthEnd}", () => {
    const r = walkScenario(patient, PICKS.probe);
    expect(r.ending).toBe("cure");
    expect(r.truth).toBeGreaterThanOrEqual(${truthEnd});
  });
});
`;
}

/** 校验患者口述零叙事时间词 */
function checkTimeWords(dialogs) {
  const hits = [];
  for (const d of dialogs) {
    const speaker = field(d.code, "speaker");
    if (speaker !== "patient") continue;
    const text = field(d.code, "text");
    if (!text) continue;
    for (const w of TIME_WORDS) {
      if (text.includes(w)) hits.push({ line: d.startLine, word: w, text: text.slice(0, 40) });
    }
  }
  return hits;
}

function main() {
  const args = process.argv.slice(2);
  const mdPath = args.find((a) => !a.startsWith("--"));
  if (!mdPath) {
    console.error("用法：node scripts/md-to-patient.mjs <剧本.md> [--out <目录>]");
    process.exit(1);
  }
  const outDir = args.includes("--out")
    ? resolve(args[args.indexOf("--out") + 1])
    : DEFAULT_OUT;
  const withWalk = args.includes("--walk");
  const src = readFileSync(resolve(REPO, mdPath), "utf8");

  // 1. 提取代码块
  const { meta, dialogs } = extractFencedBlocks(src);
  if (meta.length !== 1) {
    console.error(`ts-meta 代码块应为 1 个，实际 ${meta.length} 个`);
    process.exit(1);
  }
  if (dialogs.length === 0) {
    console.error("未找到任何 ts-dialog 代码块");
    process.exit(1);
  }
  const metaBlock = meta[0];

  // 2. 节点 id
  const sceneId = readBlockId(metaBlock, "ts-meta");
  const ids = [];
  const idSet = new Set();
  for (const d of dialogs) {
    const id = readBlockId(d, "ts-dialog");
    if (idSet.has(id)) {
      console.error(`节点 id 重复：${id}（第 ${d.startLine} 行）`);
      process.exit(1);
    }
    idSet.add(id);
    ids.push(id);
  }

  // 3. startNode 存在
  const startNode = field(metaBlock.code, "startNode");
  if (!startNode || !idSet.has(startNode)) {
    console.error(`startNode "${startNode}" 不存在于节点集（ts-meta 需含 startNode，且节点块须覆盖它）`);
    process.exit(1);
  }

  // 4. 引用无悬空 + 结构完整性
  const doctorNodeIds = [];
  for (let i = 0; i < dialogs.length; i++) {
    const d = dialogs[i];
    const refs = collectRefs(d.code);
    for (const r of refs) {
      if (!idSet.has(r.to)) {
        console.error(`节点 ${ids[i]} 的 ${r.kind} 引用 "${r.to}" 悬空（第 ${d.startLine} 行）`);
        process.exit(1);
      }
    }
    const speaker = field(d.code, "speaker");
    if (speaker === "doctor") {
      doctorNodeIds.push(ids[i]);
      // doctor 节点必须有 choices 且每条带 next
      const choices = d.code.match(/choices\s*:\s*\[([\s\S]*?)\]/);
      if (!choices) {
        console.error(`doctor 节点 ${ids[i]}（第 ${d.startLine} 行）缺少 choices`);
        process.exit(1);
      }
      // 按 choice 对象大致计数（id 字段出现次数减 1，减去节点自身 id）
      const choiceCount = (choices[1].match(/id\s*:\s*["'][^"']+["']/g) ?? []).length;
      if (choiceCount < 2) {
        console.error(`doctor 节点 ${ids[i]}（第 ${d.startLine} 行）choice 少于 2 个（实际 ${choiceCount}）`);
        process.exit(1);
      }
      const noNext = choices[1].match(/{[^{}]*?kind\s*:\s*["'][^"']+["'][^{}]*?}/g)?.filter(
        (c) => !/next\s*:/.test(c)
      ).length ?? 0;
      if (noNext > 0) {
        console.error(`doctor 节点 ${ids[i]}（第 ${d.startLine} 行）有 ${noNext} 个 choice 缺 next`);
        process.exit(1);
      }
    }
  }

  // 4.5 节拍边界 beatEnd 校验（治疗分期复诊，SPEC v1.6.0）
  const metaComments = parseMetaComments(metaBlock.code);
  const tier = metaComments.tier ?? "未知档位";
  const BEATS_BY_TIER = { 短: 4, 中: 5, 长: 6 };
  const beats = BEATS_BY_TIER[tier];
  const beatEndNodes = [];
  for (let i = 0; i < dialogs.length; i++) {
    const d = dialogs[i];
    if (!/beatEnd\s*:/.test(d.code)) continue;
    beatEndNodes.push(ids[i]);
    const speaker = field(d.code, "speaker");
    if (speaker !== "narration") {
      console.error(`节拍边界节点 ${ids[i]}（第 ${d.startLine} 行）speaker 必须是 narration（患者离开），实际 ${speaker}`);
      process.exit(1);
    }
    if (/isEnding\s*:\s*true/.test(d.code)) {
      console.error(`节拍边界节点 ${ids[i]}（第 ${d.startLine} 行）是结局节点（isEnding），不应加 beatEnd（末节拍走正常结局）`);
      process.exit(1);
    }
    const rn = d.code.match(/resumeNode\s*:\s*["'`]([^"'`]+)["'`]/);
    if (!rn) {
      console.error(`节拍边界节点 ${ids[i]}（第 ${d.startLine} 行）缺少 beatEnd.resumeNode`);
      process.exit(1);
    }
    if (!idSet.has(rn[1])) {
      console.error(`节拍边界节点 ${ids[i]}（第 ${d.startLine} 行）beatEnd.resumeNode "${rn[1]}" 悬空`);
      process.exit(1);
    }
  }
  if (beats !== undefined && beatEndNodes.length !== beats - 1) {
    console.error(`${tier}档（${beats} 节拍）节拍边界数应为 ${beats - 1}（节拍数-1），实际 ${beatEndNodes.length} 处 beatEnd`);
    process.exit(1);
  }

  // 5. 时间词
  const timeHits = checkTimeWords(dialogs);
  if (timeHits.length > 0) {
    for (const h of timeHits) {
      console.error(`患者口述含叙事时间词「${h.word}」（第 ${h.line} 行）：${h.text}…`);
    }
    process.exit(1);
  }

  // 6. 结局节点检查
  const endingNodes = dialogs.filter((d) => /isEnding\s*:\s*true/.test(d.code));
  if (endingNodes.length < 2) {
    console.error(`结局节点（isEnding: true）应 ≥ 2 个，实际 ${endingNodes.length}`);
    process.exit(1);
  }
  for (const d of endingNodes) {
    const id = readBlockId(d, "ts-dialog");
    const hasType = /endingType\s*:/.test(d.code);
    const hasReward = /endingReward\s*:/.test(d.code);
    const hasTitle = /endingTitle\s*:/.test(d.code);
    if (!(hasType && hasReward && hasTitle)) {
      console.error(`结局节点 ${id}（第 ${d.startLine} 行）需含 endingType / endingTitle / endingReward 三字段`);
      process.exit(1);
    }
  }

  // 7. 组装 TS（节点以 id: {...} 形式进入 dialogues，作为对象成员 key）
  const dialogBody = dialogs
    .map((d) => {
      const id = readBlockId(d, "ts-dialog");
      const body = d.code.replace(/\/\/ id:\s*\S+\s*\n?/, "").trimEnd();
      return `${id}: ${body}`;
    })
    .join(",\n  ");
  const metaBody = metaBlock.code.replace(/\/\/ id:\s*\S+\s*\n?/, "").trimEnd();
  const ts = `// AUTO-GENERATED by scripts/md-to-patient.mjs — 勿手改，改源剧本文档后重新生成
// 源：${mdPath}
import type { PatientScenario } from "../../types";

export const patient: PatientScenario = {
  ...${metaBody},
  dialogues: {
  ${dialogBody},
  },
};
`;
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, `${sceneId}.ts`);
  writeFileSync(outFile, ts, "utf8");

  // 8. --walk：生成走线验收测试
  let testFile = null;
  if (withWalk) {
    const p = parseMetaComments(metaBlock.code);
    const name = field(metaBlock.code, "name") ?? sceneId;
    const tier = p.tier ?? "未知档位";
    testFile = join(REPO, "lib", "data", `${sceneId}.walk.test.ts`);
    writeFileSync(testFile, buildWalkTest(sceneId, name, tier, p), "utf8");
  }

  // 9. 类型校验：tsc 全库
  try {
    execSync("npx tsc --noEmit", { cwd: REPO, stdio: "pipe" });
  } catch (e) {
    console.error("tsc --noEmit 未通过（生成的 TS 有类型错误）：");
    console.error(e.stderr?.toString() ?? e.message);
    process.exit(1);
  }

  const choiceTotal = doctorNodeIds.length;
  console.log(`✓ 生成 ${basename(outFile)}（${outDir}/${sceneId}.ts）`);
  console.log(`  ts-meta 场景 id: ${sceneId}  节点: ${dialogs.length} 个（医生节点 ${choiceTotal} 个）`);
  console.log(`  结构校验通过：id 唯一 / startNode 存在 / 引用无悬空 / 结局字段齐备 / 患者口述零叙事时间词 / 节拍边界 beatEnd 齐备`);
  if (withWalk && testFile) console.log(`✓ 生成 ${basename(testFile)}（--walk 走线验收测试）`);
  console.log(`  tsc --noEmit 通过`);
}

main();
