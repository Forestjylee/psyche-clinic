#!/usr/bin/env node
/**
 * 一次性迁移：把 lib/data/patients.ts 里的患者对象拆成 lib/data/patients/<id>.ts
 * 用法：node scripts/split-patients.mjs
 * 拆完在患者文件顶部补 import，聚合入口由后续步骤重写。
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, "..");
const SRC = join(REPO, "lib", "data", "patients.ts");
const OUT = join(REPO, "lib", "data", "patients");
mkdirSync(OUT, { recursive: true });

const src = readFileSync(SRC, "utf8");

/** 括号配平状态机：找从 braceStart 开始的配平 }；跳过字符串/注释 */
function findMatchingBrace(text, braceIdx) {
  let depth = 0;
  let i = braceIdx;
  let state = "code"; // code | sq | dq | tpl | line | block
  while (i < text.length) {
    const c = text[i];
    const n = text[i + 1];
    if (state === "code") {
      if (c === '"') state = "dq";
      else if (c === "'") state = "sq";
      else if (c === "`") state = "tpl";
      else if (c === "/" && n === "/") state = "line";
      else if (c === "/" && n === "*") state = "block";
      else if (c === "{") depth++;
      else if (c === "}") {
        depth--;
        if (depth === 0) return i;
      }
    } else if (state === "sq") {
      if (c === "\\") i++;
      else if (c === "'") state = "code";
    } else if (state === "dq") {
      if (c === "\\") i++;
      else if (c === '"') state = "code";
    } else if (state === "tpl") {
      if (c === "\\") i++;
      else if (c === "`") state = "code";
    } else if (state === "line") {
      if (c === "\n") state = "code";
    } else if (state === "block") {
      if (c === "*" && n === "/") {
        state = "code";
        i++;
      }
    }
    i++;
  }
  return -1;
}

// 找所有 `export const patientX: PatientScenario = {` 及 GUIDED_PATIENT_ID
const patientRe = /export\s+const\s+(patient[A-Z])\s*:\s*PatientScenario\s*=\s*\{/g;
const finds = [];
let m;
while ((m = patientRe.exec(src)) !== null) {
  const name = m[1];
  const objStart = m.index + m[0].length - 1; // '{' 位置
  const endIdx = findMatchingBrace(src, objStart);
  if (endIdx < 0) {
    console.error(`配平失败：${name}`);
    process.exit(1);
  }
  const objEnd = endIdx + 1; // 含 '}'
  finds.push({ name, objStart, objEnd });
}

const GID_RE = /export\s+const\s+(GUIDED_PATIENT_ID)\s*=\s*"[^"]+"/;

// 每个患者：id 从对象里提取
for (const f of finds) {
  const body = src.slice(f.objStart, f.objEnd); // { ... }
  const idm = body.match(/id\s*:\s*"([^"]+)"/);
  if (!idm) {
    console.error(`${f.name} 缺 id 字段`);
    process.exit(1);
  }
  const sceneId = idm[1];
  const gid = f.name === "patientG" ? (GID_RE.exec(src)?.[0] ?? "") : "";
  const importLine = `import type { PatientScenario } from "../../types";\n`;
  const header = `// AUTO-GENERATED by scripts/split-patients.mjs — 由 lib/data/patients.ts 拆分而来\n// 患者 id: ${sceneId}\n`;
  const constDecl = `\nexport const ${f.name}: PatientScenario = ${body};\n`;
  let content = header + importLine + (gid ? `\nexport const GUIDED_PATIENT_ID = ${/"[^"]+"/.exec(gid)?.[0]};\n` : "") + constDecl;
  if (f.name === "patientA") {
    content += `\n// 注意：patientA 另有 v3 走线测试 lib/data/lin-xiao-walk.test.ts 引用（经聚合入口）\n`;
  }
  const outFile = join(OUT, `${sceneId}.ts`);
  writeFileSync(outFile, content, "utf8");
  console.log(`✓ ${f.name} (id=${sceneId}) → ${outFile}  对象 ${f.objStart}-${f.objEnd}`);
}
